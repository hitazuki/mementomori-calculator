import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//, route => route.abort())
  await page.addInitScript(() => localStorage.setItem('mmt-calc-current-view', 'equipmentUpgrade'))
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  await page.getByText('调整参数与方案', { exact: true }).click()
})

test('equipment chart responds to baseline, reforge, incoming damage and both gear toggles', async ({ page }) => {
  const config = page.locator('.upgrade-config')
  const level = config.getByLabel('角色等级', { exact: true })
  const source = config.getByLabel('面板来源')
  await expect(source).toHaveValue('cordie')
  await expect(config.locator('output').first()).toHaveText('32,981,510')
  await level.fill('501')
  await expect(config.locator('output').first()).toHaveText('33,084,440')

  const stamina = config.getByLabel('场外耐力加成（%）')
  const hp = config.getByLabel('场外生命加成（%）')
  await stamina.fill('20')
  await hp.fill('30')
  await expect(config.locator('output').first()).toHaveText('51,611,726.4')
  await source.selectOption('custom')
  const customHp = config.getByLabel('最大生命', { exact: true })
  await customHp.fill('50000000')
  await source.selectOption('cordie')
  await source.selectOption('custom')
  await expect(customHp).toHaveValue('50000000')

  await page.getByText('展开数值与强化材料表', { exact: true }).click()
  await expect(page.locator('.upgrade-chart canvas').first()).toBeVisible()
  const first = page.locator('.upgrade-table-scroll tbody tr').first()
  const gain = first.locator('td').nth(3)
  const snapshot = await gain.textContent()
  const chart = page.locator('.upgrade-chart canvas').first()
  const chartBefore = await chart.evaluate(canvas => canvas.toDataURL())
  const plan = page.locator('.upgrade-plan').first()
  await plan.getByText(/打磨配分 · 25/).click()
  await plan.getByRole('slider').last().press('End')
  await expect(plan.getByRole('slider').last()).toHaveAttribute('aria-valuetext', '60%')
  await expect(gain).not.toHaveText(snapshot)
  await expect.poll(() => chart.evaluate(canvas => canvas.toDataURL())).not.toBe(chartBefore)
  await plan.getByRole('slider').last().press('Home')
  await expect(plan.getByRole('slider').last()).toHaveAttribute('aria-valuetext', '0%')
  await expect(first).toContainText('耐力 0')
  const physical = await gain.textContent()
  await page.getByLabel('承受伤害类型').selectOption('mag')
  await expect(gain).not.toHaveText(physical)

  await plan.getByLabel('装备部位').selectOption('accessory')
  await expect(first).toContainText(/弱化效果抗性 [1-9]/)
  await plan.getByLabel('装备基础属性').uncheck()
  await expect(first).toContainText('弱化效果抗性 0')
  await plan.getByLabel('四维附加属性').uncheck()
  await expect(gain).toContainText('0.000%')
})

test.describe('mobile equipment controls', () => {
  test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })

  test('reforge sliders fit the page and respond to touch', async ({ page }) => {
    const plan = page.locator('.upgrade-plan').first()
    await plan.getByText(/打磨配分 · 25/).tap()
    const sliders = plan.getByRole('slider')
    const stamina = sliders.last()
    const size = await stamina.boundingBox()
    await stamina.tap({ position: { x: size.width * 0.9, y: size.height / 2 } })
    await expect(stamina).not.toHaveAttribute('aria-valuetext', '25%')
    await expect.poll(async () => sliders.evaluateAll(inputs => inputs.reduce((sum, input) => sum + input.valueAsNumber, 0))).toBeCloseTo(100, 7)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  })
})
