import { test, expect } from '@playwright/test'
test('five-target Boss shares element, preserves configuration, and exposes seeded target details', async ({ page }) => {
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.route(/https:\/\/fonts\.(googleapis|gstatic)\.com\//,route=>route.abort())
  await page.addInitScript(()=>localStorage.setItem('mmt-calc-current-view','raidTable'))
  await page.goto('./',{waitUntil:'domcontentloaded'})
  const boss=page.locator('select').filter({has:page.locator('option[value="five-targets"]')})
  await boss.selectOption('five-targets')
  const element=page.locator('label').filter({hasText:'敌方统一属性'}).locator('select')
  await expect(element).toHaveValue('3')
  await expect(element.locator('option')).toHaveCount(6)
  await element.selectOption('2')
  const seed=page.locator('label').filter({hasText:'随机种子'}).locator('input')
  await expect(seed).toHaveValue('1')
  await seed.fill('42')
  await page.getByRole('button',{name:'重新抽样',exact:true}).click()
  await expect(seed).toHaveValue('43')
  await boss.selectOption('sonya')
  await expect(element).toHaveCount(0)
  await boss.selectOption('five-targets')
  await expect(element).toHaveValue('2')
  await expect(seed).toHaveValue('43')
  await page.locator('.raid-action-cell').first().click()
  await expect(page.locator('.raid-step-list').first()).toContainText('敌方')
  await page.screenshot({path:'test-results/raid-five-targets.png',fullPage:true})
  expect(errors).toEqual([])
})
